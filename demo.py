"""End-to-end demo of the PawPal+ AI planner (offline, no API key).

Usage:
    python demo.py                                  # run 3 built-in example requests
    python demo.py "senior dog with arthritis, 45 minutes"
    python demo.py --baseline "senior dog with arthritis, 45 minutes"   # no retrieval, plain explanations
    python demo.py --log                            # also append the agent traces to ai_interactions.md
"""

import sys
from pathlib import Path

from tabulate import tabulate

from pawpal_ai import AIPlanner

EXAMPLES = [
    "I have a senior dog with arthritis, I only have 45 minutes today",
    "Plan a day for my new kitten, 30 minutes available",
    "What dose of ibuprofen can I give my dog?",
    "my lab can't manage the stairs anymore and winces when he gets up, 40 minutes",
]
LOG_FILE = Path(__file__).parent / "ai_interactions.md"


def show(planner: AIPlanner, request: str, baseline: bool) -> str:
    result = planner.plan(request, use_retrieval=not baseline, style="baseline" if baseline else "specialized")
    print(f"\n{'=' * 78}\nREQUEST: {request}\n{'=' * 78}")
    if result.status == "refused":
        print(f"REFUSED: {result.message}")
    else:
        p = result.profile
        print(f"Profile: {p['species']}, {p['stage']}, conditions={p['conditions'] or 'none'}, {p['minutes']} min")
        print("Sources:", "; ".join(c.citation for c in result.retrieved) or "none")
        rows = [[e["start_time"], e["end_time"], e["task"].title, e["task"].priority, e["task"].duration_minutes]
                for e in result.plan]
        print(tabulate(rows, headers=["Start", "End", "Task", "Priority", "Min"], tablefmt="rounded_outline"))
        print(f"Confidence: {result.confidence:.2f}")
        for w in result.warnings:
            print("WARNING:", w)
        print("\nWhy this plan:\n" + result.explanation)
    print("\nAgent trace:")
    for i, step in enumerate(result.trace, 1):
        print(f"  {i}. {step['step']}: {step['detail']}")
    return result.trace_markdown(request)


def main() -> None:
    args = sys.argv[1:]
    baseline = "--baseline" in args
    log = "--log" in args
    requests = [a for a in args if not a.startswith("--")] or EXAMPLES
    planner = AIPlanner()
    blocks = [show(planner, r, baseline) for r in requests]
    if log:
        with LOG_FILE.open("a", encoding="utf-8") as f:
            f.write("\n\n## Agent trace log (generated by `python demo.py --log`)\n")
            for block in blocks:
                f.write("\n" + block + "\n\n---\n")
        print(f"\nTraces appended to {LOG_FILE.name}")


if __name__ == "__main__":
    main()
